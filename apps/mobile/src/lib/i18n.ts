export const LANGUAGES = { en, "zh-Hans": zhHans, "zh-Hant": zhHant } as const;
export type Language = keyof typeof LANGUAGES;

/** Picks a language from BCP-47 tags such as "zh-Hant-TW", "zh-CN", "en-US". */
export function pickLanguage(tags: readonly string[]): Language {
  for (const tag of tags) {
    const t = tag.toLowerCase();
    if (t.startsWith("zh")) {
      if (t.includes("hant") || t.endsWith("-tw") || t.endsWith("-hk") || t.endsWith("-mo")) return "zh-Hant";
      return "zh-Hans";
    }
    if (t.startsWith("en")) return "en";
  }
  return "en";
}

export function translator(lang: Language): (key: StringKey) => string {
  const table = LANGUAGES[lang];
  return (key) => table[key] ?? en[key];
}
