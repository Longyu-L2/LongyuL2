// Writes packages/abis/src/dex.ts (the LONGYU Swap ABIs) from the Foundry artifacts in contracts/dex/out.
// Rerun after any change to the DEX contracts:
//   cd contracts/dex && forge build && node scripts/export-abis.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const outDir = fileURLToPath(new URL("../out/", import.meta.url));
const target = fileURLToPath(new URL("../../../packages/abis/src/dex.ts", import.meta.url));

// [export name, source file, contract name]
const contracts = [
  ["uniswapV2Router02Abi", "src/periphery/UniswapV2Router02.sol", "UniswapV2Router02"],
  ["uniswapV2FactoryAbi", "src/core/UniswapV2Factory.sol", "UniswapV2Factory"],
  ["uniswapV2PairAbi", "src/core/UniswapV2Pair.sol", "UniswapV2Pair"],
  // v2-core's minimal ERC20 interface: metadata, supply, balances, allowances and transfers.
  ["minimalErc20Abi", "src/core/interfaces/IERC20.sol", "IERC20"],
];

function* artifactFiles(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === "build-info") continue;
    const path = join(dir, entry.name);
    if (entry.isDirectory()) yield* artifactFiles(path);
    else if (entry.name.endsWith(".json")) yield path;
  }
}

// Foundry nests and suffixes artifact paths when file names or compiler versions repeat, so match on the
// compilation target recorded in each artifact's metadata instead of guessing the path.
const artifacts = [...artifactFiles(outDir)].map((file) => JSON.parse(readFileSync(file, "utf8")));

function abiOf(source, name) {
  const abis = artifacts
    .filter((a) => a.metadata?.settings?.compilationTarget?.[source] === name)
    .map((a) => JSON.stringify(a.abi));
  if (abis.length === 0) throw new Error(`no artifact for ${source}:${name}; run forge build in contracts/dex`);
  if (abis.some((abi) => abi !== abis[0])) throw new Error(`artifacts for ${source}:${name} disagree`);
  return abis[0];
}

let src = "// Generated by contracts/dex/scripts/export-abis.mjs from contracts/dex/out. Do not edit by hand.\n";
src += "// LONGYU Swap: a Uniswap V2 fork (GPL-3.0-or-later); see contracts/dex/README.md.\n\n";
for (const [exportName, source, name] of contracts) {
  src += `export const ${exportName} = ${abiOf(source, name)} as const;\n\n`;
}
writeFileSync(target, src.replace(/\n\n$/, "\n"));
console.log(`exported ${contracts.length} ABIs to ${target}`);
