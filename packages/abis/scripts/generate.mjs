// Generates src/index.ts from Foundry artifacts so every app uses the exact compiled ABI.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const contracts = [
  "EmissionSchedule", "MiningVault", "MiningDistributor", "Faucet",
  "MigrationDistributor", "PaymentRouter", "LongToken",
];
const out = (name) => fileURLToPath(new URL(`../../../contracts/out/${name}.sol/${name}.json`, import.meta.url));
const lower = (s) => s[0].toLowerCase() + s.slice(1);
let src = "// Generated by scripts/generate.mjs from contracts/out. Do not edit by hand.\n\n";
for (const name of contracts) {
  const json = JSON.parse(readFileSync(out(name), "utf8"));
  src += `export const ${lower(name)}Abi = ${JSON.stringify(json.abi)} as const;\n\n`;
  src += `export const ${lower(name)}Bytecode = ${JSON.stringify(json.bytecode.object)} as const;\n\n`;
}
// LONGYU Swap ABIs come from contracts/dex/scripts/export-abis.mjs; keep re-exporting them.
src += `export * from "./dex.ts";\n`;
writeFileSync(fileURLToPath(new URL("../src/index.ts", import.meta.url)), src);
console.log(`generated ABIs for ${contracts.length} contracts`);
